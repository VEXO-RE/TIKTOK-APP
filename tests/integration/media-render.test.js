import test from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdtemp,readFile,rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join,resolve,dirname,basename } from "node:path";
import { renderVideo,validateRecipe,mediaCapabilities,toolDirectory } from "../../src/media/render.service.js";
const run=promisify(execFile);
const rights={type:"owned",evidence:"Synthetic media generated by this test"};
test("media recipe rejects unknown fields, unsafe filter expressions, invalid timeline and missing rights",()=>{
  for(const input of [{},{rights,filter:"movie=https://evil.test"},{rights,speed:99},
    {rights,start:5,end:2},{rights,format:"unknown"},{rights,imagePosition:"x=0;movie=evil"},
    {rights,overlays:[{text:"Test",start:0,end:2,color:"red:box=evil"}]},
    {rights,subtitles:[{text:"Test",start:2,end:1}]}]) {
    assert.throws(()=>validateRecipe(input),error=>error.code==="MEDIA_RECIPE_INVALID");
  }
  assert.equal(validateRecipe({rights}).schemaVersion,"1.0.0");
});
test("native renderer exports MP4/H264 with timed text, image, original audio, music and voice",async t=>{
  if(!(await mediaCapabilities()).available){t.skip("Portable FFmpeg unavailable; native render not verified.");return;}
  const directory=await mkdtemp(join(tmpdir(),"media-native-test-"));
  const ffmpeg=join(toolDirectory,"ffmpeg.exe");
  try {
    const generate=async args=>run(ffmpeg,["-hide_banner","-loglevel","error","-y",...args],{cwd:directory,windowsHide:true,timeout:30000});
    await generate(["-f","lavfi","-i","color=c=navy:s=320x240:r=30","-f","lavfi","-i","sine=frequency=440:sample_rate=44100","-t","2","-c:v","libx264","-pix_fmt","yuv420p","-c:a","aac","source.mp4"]);
    await generate(["-f","lavfi","-i","sine=frequency=600:sample_rate=44100","-t","2","-c:a","libmp3lame","music.mp3"]);
    await generate(["-f","lavfi","-i","sine=frequency=880:sample_rate=44100","-t","2","-c:a","libopus","voice.webm"]);
    await generate(["-f","lavfi","-i","color=c=red:s=64x64","-frames:v","1","logo.png"]);
    const original=await readFile(join(directory,"source.mp4"));
    const originalCopy=Buffer.from(original);
    const result=await renderVideo({buffer:original,diagnostic:message=>console.error(message),tracks:{
      music:{buffer:await readFile(join(directory,"music.mp3")),rights},
      voice:{buffer:await readFile(join(directory,"voice.webm")),rights}},
      image:{buffer:await readFile(join(directory,"logo.png")),rights},
      recipe:{rights,start:.2,end:1.8,speed:1.25,format:"square",template:"editorial",fade:.1,
        musicOffset:.1,voiceOffset:.2,overlays:[{text:'Synthetic: 50% "test"; [v]',start:0,end:1}],
        subtitles:[{text:"Synthetic subtitle",start:.2,end:1}]}});
    assert.equal(result.contentType,"video/mp4");assert.equal(result.qc.codec,"h264");
    assert.equal(result.qc.width,720);assert.equal(result.qc.height,720);assert.equal(result.qc.audio,true);
    assert.ok(result.qc.duration>1 && result.qc.duration<1.6);
    assert.match(result.hash,/^[a-f0-9]{64}$/);assert.notEqual(result.hash,result.sourceSha256);
    assert.deepEqual(original,originalCopy);
    await generate(["-f","lavfi","-i","color=c=green:s=320x240:r=30","-t","1","-c:v","libx264","-pix_fmt","yuv420p","silent.mp4"]);
    const silent=await renderVideo({buffer:await readFile(join(directory,"silent.mp4")),
      diagnostic:message=>console.error(message),recipe:{rights,format:"vertical",fit:"cover",resolution:1080,rotate:90,flip:true,speed:.5,brightness:.1,contrast:1.2,saturation:.8}});
    assert.equal(silent.qc.width,1080);assert.equal(silent.qc.height,1920);assert.equal(silent.qc.audio,false);
    assert.ok(silent.qc.duration>1.8 && silent.qc.duration<2.3);
    await assert.rejects(()=>renderVideo({buffer:original,recipe:{rights,start:10}}),error=>error.code==="MEDIA_RECIPE_INVALID");
  }finally{
    if(dirname(resolve(directory))!==resolve(tmpdir())||!basename(directory).startsWith("media-native-test-"))throw Error("Unsafe test cleanup");
    await rm(directory,{recursive:true,force:true});
  }
});
